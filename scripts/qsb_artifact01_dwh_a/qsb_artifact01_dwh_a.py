def insert_relations(con: sqlite3.Connection, records_by_filename: dict[str, dict[str, str | int]]) -> None:
    for idx, (source_name, target_name, relation_type, label) in enumerate(RELATION_RULES, start=1):
        source = records_by_filename.get(source_name)
        target = records_by_filename.get(target_name)
        if not source or not target:
            continue
        con.execute(
            """
            INSERT INTO qsb_artifact_relation (
                relation_id, source_artifact_id, target_artifact_id,
                relation_type, relation_label, status
            )
            VALUES (?, ?, ?, ?, ?, ?)
            """,
            (
                f"QSB-ARTIFACT01-REL-{idx:03d}",
                str(source["artifact_id"]),
                str(target["artifact_id"]),
                relation_type,
                label,
                "active",
            ),
        )


def count_rows(con: sqlite3.Connection) -> dict[str, int]:
    tables = [
        "qsb_artifact",
        "qsb_artifact_version",
        "qsb_artifact_lineage",
        "qsb_artifact_relation",
        "qsb_artifact_alias",
        "qsb_artifact_text_index",
        "qsb_artifact_claim_boundary",
        "qsb_artifact_export",
        "qsb_artifact_review",
        "qsb_artifact_validation_result",
    ]
    return {table: int(con.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]) for table in tables}


def scalar(con: sqlite3.Connection, query: str, params: tuple[object, ...] = ()) -> int:
    return int(con.execute(query, params).fetchone()[0])


