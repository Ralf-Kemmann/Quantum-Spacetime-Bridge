def insert_text_index(con: sqlite3.Connection, record: dict[str, str | int]) -> None:
    artifact_id = str(record["artifact_id"])
    path = Path(record["path"])
    suffix = path.suffix.lower()
    if suffix == ".sqlite":
        text_role = "binary_notice"
        text_hash = None
        excerpt = "SQLite binary registered; no text extraction in this dry run."
        extraction_method = None
        extraction_status = "not_text_extractable"
    elif suffix in {".md", ".mmd"}:
        text = path.read_text(encoding="utf-8")
        text_role = "full_text"
        text_hash = sha256_text(text)
        excerpt = normalize_excerpt(text)
        extraction_method = "direct_text_read"
        extraction_status = "extracted"
    elif suffix == ".json":
        text = path.read_text(encoding="utf-8")
        text_role = "summary"
        text_hash = sha256_text(text)
        excerpt = normalize_excerpt(text)
        extraction_method = "direct_text_read"
        extraction_status = "extracted"
    elif suffix == ".sql":
        text = path.read_text(encoding="utf-8")
        text_role = "full_text"
        text_hash = sha256_text(text)
        excerpt = normalize_excerpt(text)
        extraction_method = "direct_text_read"
        extraction_status = "extracted"
    else:
        text_role = "unclassified"
        text_hash = None
        excerpt = "No text extraction rule for this artifact extension."
        extraction_method = None
        extraction_status = "not_text_extractable"
    con.execute(
        """
        INSERT INTO qsb_artifact_text_index (
            text_index_id, artifact_id, text_role, language, extracted_text_path,
            text_hash, excerpt, extraction_method, extraction_status
        )
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
        """,
        (
            f"{artifact_id}-TEXT-001",
            artifact_id,
            text_role,
            "en",
            str(record["canonical_path"]) if extraction_status == "extracted" else None,
            text_hash,
            excerpt,
            extraction_method,
            extraction_status,
        ),
    )


